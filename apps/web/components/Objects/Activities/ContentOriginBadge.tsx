'use client'

import React from 'react'
import { BookOpen, Sparkles, UserRound } from 'lucide-react'
import { useTranslation } from 'react-i18next'

interface ContentOriginBadgeProps {
  aiGenerated?: boolean
  sources?: string[]
  className?: string
}

/**
 * Small provenance label shown on lessons and tasks. AI-generated material is
 * marked explicitly; everything without that flag is teacher-authored.
 */
export default function ContentOriginBadge({ aiGenerated, sources = [], className = '' }: ContentOriginBadgeProps) {
  const { t } = useTranslation()

  if (aiGenerated) {
    return (
      <span className={`inline-flex flex-wrap items-center gap-1 ${className}`}>
        <span
          className="inline-flex items-center gap-1 rounded-full border border-violet-200 bg-violet-50 px-2 py-0.5 text-[11px] font-semibold text-violet-700"
          title={t('activities.ai_generated_hint', {
            defaultValue: 'This material was generated by AI.',
          })}
        >
          <Sparkles size={12} />
          {t('activities.ai_generated', { defaultValue: 'AI-generated' })}
        </span>
        {sources.length > 0 ? (
          <span
            className="inline-flex max-w-[360px] items-center gap-1 truncate rounded-full border border-sky-200 bg-sky-50 px-2 py-0.5 text-[11px] font-semibold text-sky-700"
            title={sources.join(', ')}
          >
            {t('activities.from_materials', { defaultValue: 'From materials' })}: {sources.join(', ')}
          </span>
        ) : null}
      </span>
    )
  }

  if (sources.length > 0) {
    return (
      <span
        className={`inline-flex max-w-[420px] items-center gap-1 truncate rounded-full border border-sky-200 bg-sky-50 px-2 py-0.5 text-[11px] font-semibold text-sky-700 ${className}`}
        title={sources.join(', ')}
      >
        <BookOpen size={12} />
        {t('activities.from_materials', { defaultValue: 'From materials' })}: {sources.join(', ')}
      </span>
    )
  }

  return (
    <span
      className={`inline-flex items-center gap-1 rounded-full border border-slate-200 bg-slate-50 px-2 py-0.5 text-[11px] font-semibold text-slate-600 ${className}`}
      title={t('activities.from_teacher_hint', {
        defaultValue: 'This material was created by a teacher.',
      })}
    >
      <UserRound size={12} />
      {t('activities.from_teacher', { defaultValue: 'From teacher' })}
    </span>
  )
}
